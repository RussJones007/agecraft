test_that("weeks are opt-in and calendar units have explicit priority", {
  birth <- as.Date("2024-01-01")
  event <- birth + c(0, 6, 7, 27, 28, 30, 31, 365, 366, NA)
  x <- age_auto_unit(birth, event, c("year", "month", "week", "day"))
  expect_identical(unname(x), c(0, 6, 1, 3, 4, 4, 1, 11, 1, NA_real_))
  expect_named(x, c("Day", "Day", "Week", "Week", "Week", "Week", "Month", "Month", "Year", ""))
  expect_identical(unname(age_auto_unit(birth, birth + 30)), 30)
  expect_identical(names(age_auto_unit(birth, birth + 30)), "Day")
  expect_identical(unname(age_auto_unit(birth, birth + 366, c("day", "week"))), 52)
  expect_error(age_auto_unit(birth, event, "week"), "must contain day")
  expect_error(age_auto_unit(birth, event, c("day", "hour")), "must contain day")
  expect_length(age_auto_unit(as.Date(character()), birth, c("day", "week")), 0)
  expect_error(age_auto_unit(birth, birth - 1, c("day", "week")), "precede")
})
