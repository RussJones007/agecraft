test_that("categories retain definitions and ordinary factor display", {
  g <- age_interval(c(0, 5, 10), c(5, 10, Inf), sep = " to ")
  x <- age_group(c("5 to 9", NA, "0 to 4"), g)
  expect_s3_class(x, "age_group")
  expect_true(is.ordered(x))
  expect_identical(as.character(x), c("5 to 9", NA, "0 to 4"))
  expect_identical(group_intervals(x), g)
  expect_identical(levels(x[1]), levels(x))
  expect_identical(group_intervals(x[1]), g)
  expect_identical(group_intervals(droplevels(x[1])), g[2])
  expect_length(group_intervals(droplevels(x[FALSE])), 0)
  expect_identical(levels(x[FALSE]), levels(x))
  expect_identical(as.character(rep(x, 2)), rep(as.character(x), 2))
  expect_identical(as.character(x[[1]]), "5 to 9")
  expect_identical(class(as.factor(x)), "factor")
  expect_identical(class(as.ordered(x)), c("ordered", "factor"))
  expect_error(age_group("unknown", g), "Unknown")
  expect_error(age_group(character(), g[c(2, 1)]), "chronological")
  expect_error(age_group(character(), age_interval(NA_real_, NA_real_)), "present")
  expect_length(age_group(character(), age_interval(numeric(), numeric())), 0)
})

test_that("level edits and replacement preserve mappings", {
  g <- age_interval(c(0, 5), c(5, Inf))
  x <- age_group(c("0-4", "5+"), g)
  levels(x) <- c("Young", "Older")
  expect_identical(names(group_intervals(x)), levels(x))
  expect_identical(ivs::iv_start(group_intervals(x)), c(0, 5))
  expect_error(levels(x) <- c("Same", "Same"), "unique")
  expect_error(levels(x) <- rev(levels(x)), "reordering")
  expect_error(levels(x) <- c("Young", NA), "unique")
  x[1] <- "Older"
  expect_identical(as.character(x), c("Older", "Older"))
  expect_error(x[1] <- "Unknown", "existing")
  x[2] <- NA
  expect_true(is.na(x[2]))
})

test_that("base and vctrs operations require compatible definitions", {
  g <- age_interval(c(0, 5), c(5, Inf))
  x <- age_group(c("0-4", "5+"), g)
  expect_identical(as.character(c(x, x)), rep(as.character(x), 2))
  expect_identical(as.character(vctrs::vec_c(x, x)), rep(as.character(x), 2))
  expect_identical(group_intervals(vctrs::vec_slice(x, 2)), g)
  expect_identical(group_intervals(vctrs::vec_c(x, x)), group_intervals(c(x, x)))
  y <- age_group("0 to 4", age_interval(c(0, 5), c(5, Inf), sep = " to "))
  # Give matching labels while retaining different cosmetic symbols.
  levels(y) <- levels(x)
  expect_identical(attr(group_intervals(c(x, y)), "symbols"), attr(g, "symbols"))
  names(g) <- c("0-4", "5+")
  attr(g, "unit") <- "year"
  z <- age_group("0-4", g)
  expect_error(c(x, z), "must match")
  expect_error(vctrs::vec_c(x, z), "must match")
  expect_error(c(x, "0-4"), "explicitly|Can.t combine")
  changed <- age_interval(c(0, 6), c(6, Inf))
  names(changed) <- levels(x)
  expect_error(c(x, age_group("0-4", changed)), "must match")
  expect_s3_class(vctrs::vec_rbind(data.frame(a = x), data.frame(a = x))$a, "age_group")
})

test_that("categorize_age retains labels, definitions and matching policies", {
  x <- categorize_age(c(0, 4, 5, 9, 10, NA), by = c(0, 5, 10, Inf), sep = " to ")
  expect_s3_class(x, "age_group")
  expect_identical(as.character(x), c("0 to 4", "0 to 4", "5 to 9", "5 to 9", "10 +", NA))
  expect_identical(ivs::iv_start(group_intervals(x)), c(0, 5, 10))
  expect_identical(levels(x[1]), levels(x))
  expect_length(group_intervals(categorize_age(numeric())), 8)
  g <- age_interval(c(0, 5), c(5, Inf), unit = "week")
  y <- categorize_age(age(c(1, 35), unit = "day"), by = g)
  expect_identical(attr(group_intervals(y), "unit"), "week")
  expect_identical(attr(y, "units"), "day")
  expect_identical(ivs::iv_end(group_intervals(y)), c(5, Inf))
  inherited <- categorize_age(age(1, unit = "day"), by = age_interval(0, 5))
  expect_identical(attr(group_intervals(inherited), "unit"), "day")
  duplicate <- age_interval(c(0, 0), c(5, 5))
  expect_length(group_intervals(categorize_age(1, by = duplicate, multiple = "first")), 1)
  names(duplicate) <- c("A", "B")
  expect_identical(levels(categorize_age(1, by = duplicate, multiple = "last")), c("A", "B"))
  gap <- categorize_age(c(2, 7, NA), by = age_interval(0, 5))
  expect_identical(is.na(gap), c(FALSE, TRUE, TRUE))
  expect_identical(as.character(categorize_age(ivs::iv(0, 2), by = age_interval(0, 5))), "0-4")
})

test_that("restoration, comparison and names do not lose interval meaning", {
  g <- age_interval(c(0, 5), c(5, Inf))
  x <- age_group(c(a = "5+", b = "0-4", c = NA), g)
  expect_identical(names(x[2:1]), c("b", "a"))
  expect_identical(names(vctrs::vec_slice(x, 2:1)), c("b", "a"))
  expect_identical(names(c(x[1], x[2])), c("a", "b"))
  expect_identical(names(vctrs::vec_cast(x, x[0])), names(x))
  expect_identical(as.character(sort(x)), c("0-4", "5+"))
  expect_identical(x < x, c(FALSE, FALSE, NA))
  expect_error(vctrs::vec_c(x, factor("5+")), "explicitly|Can.t combine")
  expect_error(vctrs::vec_c(factor("5+"), x), "explicitly|Can.t combine")
  expect_error(vctrs::vec_c(x, "5+"), "explicitly|Can.t combine")
  changed <- age_interval(c(0, 6), c(6, Inf))
  names(changed) <- levels(x)
  y <- age_group("5+", changed)
  expect_error(x == y, "must match")
  expect_error(x[1] <- y, "must match")
  x[[1]] <- "0-4"
  expect_identical(as.character(x[1]), "0-4")
  expect_output(print(x), "Levels:")
  expect_false(any(grepl('attr', capture.output(print(x)))))
  broken <- x
  attr(broken, "intervals") <- g[1]
  expect_error(group_intervals(broken), "mapping")
})

test_that("vctrs type descriptions use category-definition units", {
  x <- categorize_age(age(c(1, NA), unit = "day"),
                      by = age_interval(0, Inf, unit = "week"))
  for (value in list(x, x[0], x[2])) {
    expect_identical(vctrs::vec_ptype_full(value), "age_group [week]")
    expect_identical(vctrs::vec_ptype_abbr(value), "aGrp-week")
  }
  unitless <- age_group("0-4", age_interval(0, 5))
  expect_identical(vctrs::vec_ptype_full(unitless), "age_group [unspecified]")
  expect_identical(vctrs::vec_ptype_abbr(unitless), "aGrp-unk")
})

test_that("printing identifies the class and category-definition unit", {
  x <- categorize_age(age(c(1, 2), unit = "day"),
                      by = age_interval(0, Inf, unit = "week"))
  expect_identical(capture.output(print(x))[1], "<age_group (week) [2]>")
  expect_identical(capture.output(print(x[FALSE]))[1], "<age_group (week) [0]>")
  expect_identical(capture.output(print(x[NA_integer_]))[1], "<age_group (week) [1]>")
  unitless <- age_group("0-4", age_interval(0, 5))
  expect_identical(capture.output(print(unitless))[1],
                   "<age_group (unknown) [1]>")
  result <- withVisible(print(x))
  expect_identical(result$value, x)
  expect_false(result$visible)
  expect_identical(capture.output(print(x))[-1],
                   capture.output(print(generics::as.ordered(x))))
})

test_that("structural edits are explicit and observation units are separate", {
  x <- categorize_age(age(c(1, 2), unit = "day"), by = age_interval(0, Inf, unit = "week"))
  y <- categorize_age(age(1, unit = "week"), by = age_interval(0, Inf, unit = "week"))
  combined <- c(x, y)
  expect_null(attr(combined, "units"))
  expect_identical(attr(group_intervals(combined), "unit"), "week")
  expect_null(attr(vctrs::vec_c(x, y), "units"))
  expect_error(stats::reorder(x, c(2, 1)), "chronological")
  expect_error(stats::relevel(x, ref = levels(x)[1]), "chronological")
  expect_error(droplevels(x, exclude = "0+"), "exclude")
  expect_identical(as.character(categorize_age(c(1, NA), by = age_interval(c(0, NA), c(5, NA)))), c("0-4", NA))
  expect_identical(group_intervals(x[FALSE]), group_intervals(x))
  expect_identical(group_intervals(vctrs::vec_init(x, 2)), group_intervals(x))
  expect_true(all(is.na(vctrs::vec_init(x, 2))))
})
