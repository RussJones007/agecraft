test_that("categories retain definitions and ordinary factor display", {
  g <- age_group(c(0, 5, 10), c(5, 10, Inf), sep = " to ")
  x <- age_category(c("5 to 9", NA, "0 to 4"), g)
  expect_s3_class(x, "age_category")
  expect_true(is.ordered(x))
  expect_identical(as.character(x), c("5 to 9", NA, "0 to 4"))
  expect_identical(category_groups(x), g)
  expect_identical(levels(x[1]), levels(x))
  expect_identical(category_groups(x[1]), g)
  expect_identical(category_groups(droplevels(x[1])), g[2])
  expect_length(category_groups(droplevels(x[FALSE])), 0)
  expect_identical(levels(x[FALSE]), levels(x))
  expect_identical(as.character(rep(x, 2)), rep(as.character(x), 2))
  expect_identical(as.character(x[[1]]), "5 to 9")
  expect_identical(class(as.factor(x)), "factor")
  expect_identical(class(as.ordered(x)), c("ordered", "factor"))
  expect_error(age_category("unknown", g), "Unknown")
  expect_error(age_category(character(), g[c(2, 1)]), "chronological")
  expect_error(age_category(character(), age_group(NA_real_, NA_real_)), "present")
  expect_length(age_category(character(), age_group(numeric(), numeric())), 0)
})

test_that("level edits and replacement preserve mappings", {
  g <- age_group(c(0, 5), c(5, Inf))
  x <- age_category(c("0-4", "5+"), g)
  levels(x) <- c("Young", "Older")
  expect_identical(names(category_groups(x)), levels(x))
  expect_identical(ivs::iv_start(category_groups(x)), c(0, 5))
  expect_error(levels(x) <- c("Same", "Same"), "unique")
  expect_error(levels(x) <- rev(levels(x)), "reordering")
  expect_error(levels(x) <- c("Young", NA), "unique")
  x[1] <- "Older"
  expect_identical(as.character(x), c("Older", "Older"))
  expect_error(x[1] <- "Unknown", "existing")
  x[2] <- NA
  expect_true(is.na(x[2]))
})

test_that("base and vctrs operations require compatible definitions", {
  g <- age_group(c(0, 5), c(5, Inf))
  x <- age_category(c("0-4", "5+"), g)
  expect_identical(as.character(c(x, x)), rep(as.character(x), 2))
  expect_identical(as.character(vctrs::vec_c(x, x)), rep(as.character(x), 2))
  expect_identical(category_groups(vctrs::vec_slice(x, 2)), g)
  expect_identical(category_groups(vctrs::vec_c(x, x)), category_groups(c(x, x)))
  y <- age_category("0 to 4", age_group(c(0, 5), c(5, Inf), sep = " to "))
  # Give matching labels while retaining different cosmetic symbols.
  levels(y) <- levels(x)
  expect_identical(attr(category_groups(c(x, y)), "symbols"), attr(g, "symbols"))
  names(g) <- c("0-4", "5+")
  attr(g, "unit") <- "year"
  z <- age_category("0-4", g)
  expect_error(c(x, z), "must match")
  expect_error(vctrs::vec_c(x, z), "must match")
  expect_error(c(x, "0-4"), "explicitly")
  changed <- age_group(c(0, 6), c(6, Inf))
  names(changed) <- levels(x)
  expect_error(c(x, age_category("0-4", changed)), "must match")
  expect_s3_class(vctrs::vec_rbind(data.frame(a = x), data.frame(a = x))$a, "age_category")
})
