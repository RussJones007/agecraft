test_that("age stores fractional precision with one validated time unit", {
  x <- age(c(0.02, 0.5, 2.75, NA_real_), "years")
  expect_s3_class(x, "age")
  expect_s3_class(x, "vctrs_vctr")
  expect_true(is_age(x))
  expect_true(is.numeric(x))
  expect_identical(attr(x, "unit"), "year")
  expect_identical(as.numeric(x), c(0.02, 0.5, 2.75, NA_real_))
  expect_identical(as.integer(x), c(0L, 0L, 2L, NA_integer_))
  expect_identical(format(x), c("0 year", "0 year", "2 year", NA_character_))
  expect_identical(format(x, fractional = TRUE), c("0.02 year", "0.50 year", "2.75 year", NA_character_))
  expect_output(print(x), "2 year")
  expect_length(age(), 0)
  expect_identical(as.numeric(age(1:3)), c(1, 2, 3))
  expect_false(is_age(2.5))
  expect_error(age(-1), "nonnegative")
  expect_error(age(Inf), "finite")
  expect_error(age("2.5"), "numeric")
  expect_error(age(as.Date("2024-01-01")), "numeric")
  expect_error(age(matrix(1:4, 2)), "numeric")
  expect_error(age(1, NULL), "one time-unit")
  expect_error(age(1, c("day", "year")), "one time-unit")
  expect_error(age(1, NA_character_), "one time-unit")
  expect_error(age(1, "metre"), "Unsupported")
  expect_error(format(x, fractional = NA), "TRUE or FALSE")
})

test_that("vctrs operations retain units, precision and names", {
  x <- age(c(older = 2.75, younger = 0.5), "year")
  expect_identical(as.numeric(sort(x)), c(0.5, 2.75))
  expect_identical(names(sort(x)), c("younger", "older"))
  expect_identical(names(x[2:1]), c("younger", "older"))
  expect_identical(attr(x[c(1, NA)], "unit"), "year")
  expect_identical(as.numeric(x[c(1, NA)]), c(2.75, NA_real_))
  expect_identical(vctrs::vec_c(x, x), rep(x, 2))
  expect_identical(vctrs::vec_cast(x, age()), x)
  expect_identical(vctrs::vec_cast(x, double()), vctrs::vec_data(x))
  bound <- vctrs::vec_rbind(data.frame(a = x), data.frame(a = x))
  expect_identical(as.numeric(bound$a), rep(c(2.75, 0.5), 2))
  expect_identical(attr(bound$a, "unit"), "year")
  expect_identical(x < age(1), c(FALSE, TRUE))
  expect_identical(as.numeric(mean(x)), mean(c(2.75, 0.5)))
  expect_identical(as.numeric(floor(x)), c(2, 0))
  expect_error(vctrs::vec_c(x, age(1, "day")), "incompatible units")
  expect_error(vctrs::vec_cast(x, age(unit = "day")), "incompatible units")
  expect_error(x < age(1, "day"), "incompatible units")
  expect_error(vctrs::vec_c(x, 1), class = "vctrs_error_incompatible_type")
  expect_error(x + 1, class = "vctrs_error_incompatible_op")
  expect_error(log(x), "not defined for ages")
  expect_error(sum(x), "not defined for ages")
})

test_that("explicit age conversions normalize units and guard approximation", {
  expect_identical(as_age(c(1, 2)), age(c(1, 2)))
  expect_identical(as_age(1L, "days"), age(1, "day"))
  x <- age(c(a = 1.5, b = NA_real_), "week")
  expect_identical(as_age(x), x)
  expect_identical(as_age(x, "weeks"), x)
  converted <- as_age(x, "day")
  expect_identical(as.numeric(converted), c(10.5, NA_real_))
  expect_identical(names(converted), names(x))
  expect_identical(attr(converted, "unit"), "day")
  expect_identical(as_age(units::set_units(1.5, "week")), age(1.5, "week"))
  expect_identical(as_age(units::set_units(1.5, "week"), "day"), age(10.5, "day"))
  expect_error(as_age(x, "year"), "approximate")
  expect_identical(attr(as_age(x, "year", allow_approx = TRUE), "unit"), "year")
  expect_error(as_age(units::set_units(1, "kg")), "cannot convert")
  expect_error(as_age(as.Date("2024-01-01")), "Cannot convert")
  expect_error(as_age("2.5"), "Cannot convert")
  expect_error(as_age(x, allow_approx = NA), "TRUE or FALSE")
})

test_that("classification uses fractional age values and explicit units", {
  groups <- age_group(c(0, 0.077, 1), c(0.077, 1, 3), unit = "year")
  names(groups) <- c("Neonate", "Infant", "Toddler")
  x <- age(c(0, 0.0769, 0.077, 0.5, 1, 3, NA), "year")
  expected <- c("Neonate", "Neonate", "Infant", "Infant", "Toddler", NA, NA)
  expect_identical(as.character(categorize_age(x, by = groups)), expected)
  expect_identical(as.character(age_cat_iv(x, groups)), expected)
  expect_true(is.ordered(categorize_age(x, by = groups)))
  expect_identical(names(categorize_age(x, by = groups, output = "interval")), expected)
  expect_identical(attr(categorize_age(x, by = groups), "units"), "year")
  expect_identical(as.character(categorize_age(age(c(0.2, 0.6)), by = c(0, 0.5, 1))),
                   c("[0, 0.5)", "[0.5, 1)"))
  weeks <- age_group(c(0, 1), c(1, 2), unit = "week")
  days <- age(c(3.5, 7, 14), "day")
  expect_identical(as.character(categorize_age(days, by = weeks)), c("0", "1", NA))
  expect_identical(as.character(age_cat_iv(days, weeks)), c("0", "1", NA))
  expect_identical(as.character(categorize_age(days, by = weeks, convert_units = "group_to_age")), c("0", "1", NA))
  expect_error(categorize_age(days, by = weeks, convert_units = "none"), "not compatible")
  expect_error(categorize_age(days, by = groups), "approximate")
  expect_identical(as.character(categorize_age(days, by = groups, allow_approx = TRUE)), rep("Neonate", 3))
  expect_length(categorize_age(age(), by = groups), 0)
})
