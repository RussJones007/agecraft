test_that("crosswalk retains source boundaries and endpoint rules", {
  x <- age_group(c(0, 18), c(18, 65), unit = "year")
  y <- age_group(c(0, 5, 25), c(5, 25, 65), unit = "year")
  cw <- compare_age_groups(x, y)
  expect_identical(cw$x_id, c(1L, 1L, 2L, 2L))
  expect_identical(cw$y_id, c(1L, 2L, 2L, 3L))
  expect_identical(as.character(cw$intersection), c("0-4", "5-17", "18-24", "25-64"))
  expect_identical(attr(cw$intersection, "unit"), "year")
  all <- compare_age_groups(x, y, keep_empty = TRUE)
  expect_equal(sum(all$status == "empty"), 2)
  expect_equal(nrow(compare_age_groups(age_group(0, 5), age_group(5, 10))), 0)
  expect_identical(compare_age_groups(age_group(NA_real_, NA_real_), age_group(0, 5), keep_empty = TRUE)$status, "missing")
  expect_equal(nrow(compare_age_groups(x[FALSE], y[FALSE])), 0)
  expect_error(compare_age_groups(x, age_group(0, 5, unit = "day")), "incompatible units")
  expect_error(compare_age_groups(x, age_group(0, 5)), "incompatible units")
})

test_that("membership distinguishes containment, overlap and missing evidence", {
  x <- age_group(c(3, 5, NA_real_), c(7, 8, NA_real_))
  y <- age_group(0, 5)
  expect_identical(compare_age_groups(x, y, "membership")$member, c(FALSE, FALSE, NA))
  expect_identical(compare_age_groups(x, y, "membership", membership = "possible")$member, c(TRUE, FALSE, NA))
  targets <- age_group(c(0, 2), c(10, 8))
  expect_warning(compare_age_groups(x, targets, "membership", ambiguous = "warn"), "multiple")
  expect_error(compare_age_groups(x, targets, "membership", ambiguous = "error"), "multiple")
})

test_that("set operations preserve gaps and width is in age coordinates", {
  x <- age_group(0, 20, unit = "year")
  y <- age_group(5, 10, unit = "year")
  expect_identical(as.character(compare_age_groups(x, y, "difference")), c("0-4", "10-19"))
  expect_identical(as.character(compare_age_groups(x, y, "intersection")), "5-9")
  separated <- age_group(c(0, 15), c(5, 20), unit = "year")
  expect_identical(as.character(compare_age_groups(separated, y, "union")), c("0-9", "15-19"))
  expect_equal(compare_age_groups(x, operation = "width"), units::set_units(20, "year"))
  expect_identical(compare_age_groups(age_group(c(0, NA), c(Inf, NA)), operation = "width"), c(Inf, NA_real_))
})

test_that("ordering and gap bounds retain uncertainty", {
  x <- age_group(10, 15, unit = "year")
  y <- age_group(c(0, 12, 15), c(10, 20, Inf), unit = "year")
  expect_identical(compare_age_groups(x, y, "ordering")$ordering, c("after", "unresolved", "before"))
  expect_error(compare_age_groups(x, y, "ordering", ambiguous = "error"), "unresolved")
  gap <- compare_age_groups(x, y, "age_gap")
  expect_identical(gap$lower, c(-15, -3, 0))
  expect_identical(gap$upper, c(0, 10, Inf))
  expect_false(any(gap$lower_inclusive | gap$upper_inclusive))
  expect_identical(gap$unit, rep("year", 3))
})
